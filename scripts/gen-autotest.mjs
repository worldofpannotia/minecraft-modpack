/**
 * Generates the in-game test datapack (tests/autotest/datapack) from the pack's own data.
 *
 *   node scripts/gen-autotest.mjs                    regenerate the datapack
 *   node scripts/gen-autotest.mjs --refresh-vanilla  re-snapshot vanilla item tags (needs Java + network)
 *
 * Recipes, loot tables and tags are read from client/overrides/datapacks, so the tests follow the pack
 * as it changes. See tests/autotest/README.md for how to run it.
 */
import path from 'node:path';
import {LAB, LOOT_LAB, NS, DataPack, at} from './autotest/pack.mjs';
import {PATHS, loadDatapacks, loadVanillaItemTags, makeTagResolver, refreshVanillaTags} from './autotest/sources.mjs';
import {buildRecipeSuite} from './autotest/recipes.mjs';
import {buildHeadSuite, buildMobDropSuite, buildBlockLootSuite} from './autotest/loot.mjs';
import {buildTagSuite, buildStackSuite, buildLoadSuite} from './autotest/misc.mjs';

const OUT = path.join(PATHS.root, 'tests', 'autotest', 'datapack');

if (process.argv.includes('--refresh-vanilla')) {
    await refreshVanillaTags();
    process.exit(0);
}

const {recipes, lootTables, tags} = await loadDatapacks();
const resolveTag = makeTagResolver(await loadVanillaItemTags(), tags);

const pack = new DataPack();

// ---- suites ----
const recipeStats = buildRecipeSuite(pack, {recipes, resolveTag});
const headStats = buildHeadSuite(pack, {lootTables});
buildMobDropSuite(pack, {lootTables});
buildBlockLootSuite(pack);
const tagCount = await buildTagSuite(pack);
const stackCount = await buildStackSuite(pack);
const objectiveCount = await buildLoadSuite(pack);

// ---- plumbing ----
const ROLL = at(LOOT_LAB.chest);
const lab = {
    x1: Math.floor((LAB.x - 8) / 16) * 16,
    z1: Math.floor((LAB.z - 40) / 16) * 16,
    x2: LAB.x + LAB.cols * LAB.cellX + 16,
    z2: LAB.z + Math.ceil((recipeStats.crafts + recipeStats.cooks) / LAB.cols) * LAB.cellZ + 16,
};
const FORCELOAD = `${lab.x1} ${lab.z1} ${lab.x2} ${lab.z2}`;

pack.json('pack.mcmeta', {
    pack: {
        description: 'World of Pannotia automated in-game tests (generated by scripts/gen-autotest.mjs)',
        min_format: 107,
        max_format: [107, 1],
    },
});

const score = (who) => `{"score":{"name":"${who}","objective":"${NS}"}`;

pack.fn('lib/begin', [
    `scoreboard objectives add ${NS} dummy "Autotest"`,
    ...['#pass', '#fail', '#skip', '#done'].map((w) => `scoreboard players set ${w} ${NS} 0`),
    `data modify storage ${NS}:out failures set value []`,
    `data modify storage ${NS}:out skipped set value []`,
    'tag @a remove autotest.runner',
    'tag @s[type=player] add autotest.runner',
    `tellraw @a {"text":"[autotest] preparing the lab (Overworld, ${LAB.x} ${LAB.y} ${LAB.z})...","color":"gray"}`,
    `execute in minecraft:overworld run forceload add ${FORCELOAD}`,
    `schedule function ${NS}:lib/await_lab 20t`,
]);

pack.fn('lib/await_lab', [
    `execute if loaded ${lab.x1} ${LAB.y} ${lab.z1} if loaded ${lab.x2} ${LAB.y} ${lab.z2} if loaded ${at(LOOT_LAB.chest)} run return run function ${NS}:lib/lab_ready`,
    `schedule function ${NS}:lib/await_lab 10t`,
]);

pack.fn('lib/lab_ready', [
    `fill ${LOOT_LAB.victim.x - 2} ${LAB.y - 1} ${LOOT_LAB.victim.z - 2} ${LOOT_LAB.block.x + 2} ${LAB.y - 1} ${LOOT_LAB.victim.z + 2} minecraft:stone`,
    `fill ${LOOT_LAB.victim.x - 2} ${LAB.y} ${LOOT_LAB.victim.z - 2} ${LOOT_LAB.block.x + 2} ${LAB.y + 2} ${LOOT_LAB.victim.z + 2} minecraft:air`,
    `setblock ${ROLL} minecraft:chest`,
    `tellraw @a {"text":"[autotest] lab ready, running tests...","color":"gray"}`,
    `schedule function ${NS}:lib/next 5t`,
]);

pack.fn('lib/next', [
    `execute unless data storage ${NS}:q stages[0] run return run function ${NS}:lib/finish`,
    `data modify storage ${NS}:q stage set from storage ${NS}:q stages[0]`,
    `data remove storage ${NS}:q stages[0]`,
    `function ${NS}:lib/call with storage ${NS}:q stage`,
]);

pack.fn('lib/call', ['$function $(f)']);

pack.fn('lib/finish', [
    'kill @e[tag=autotest.victim]',
    `execute in minecraft:overworld run forceload remove ${FORCELOAD}`,
    `execute if score #skip ${NS} matches 1.. run tellraw @a [{"text":"[autotest] ","color":"yellow"},${score('#skip')},"color":"yellow"},{"text":" check(s) skipped because no player started the run. Start it yourself with /function ${NS}:run","color":"yellow"}]`,
    `execute if score #fail ${NS} matches 0 run tellraw @a [{"text":"[autotest] DONE: ","color":"green"},${score('#pass')},"color":"green"},{"text":" passed, no failures","color":"green"}]`,
    `execute if score #fail ${NS} matches 1.. run tellraw @a [{"text":"[autotest] DONE: ","color":"red"},${score('#pass')},"color":"green"},{"text":" passed, ","color":"green"},${score('#fail')},"color":"red"},{"text":" FAILED. List them again with /function ${NS}:failures","color":"red"}]`,
    `scoreboard players set #done ${NS} 1`,
    'tag @a remove autotest.runner',
]);

pack.fn('lib/pass', [`scoreboard players add #pass ${NS} 1`]);

pack.fn('lib/fail', [
    `$tellraw @a [{"text":"[autotest] FAIL ","color":"red"},{"text":"$(id)","color":"white"},{"text":"  - $(why)","color":"gray"}]`,
    `$data modify storage ${NS}:out failures append value {id:"$(id)",why:"$(why)"}`,
    `scoreboard players add #fail ${NS} 1`,
]);

pack.fn('lib/skip', [`scoreboard players add #skip ${NS} 1`, `$data modify storage ${NS}:out skipped append value "$(id)"`]);

pack.fn('lib/check_score', [
    `$execute store success score #ok ${NS} if score $(who) ${NS} matches $(lo)..$(hi)`,
    `execute if score #ok ${NS} matches 1 run return run scoreboard players add #pass ${NS} 1`,
    `$tellraw @a [{"text":"[autotest] FAIL ","color":"red"},{"text":"$(id)","color":"white"},{"text":"  - got ","color":"gray"},{"score":{"name":"$(who)","objective":"${NS}"},"color":"yellow"},{"text":", expected $(lo)..$(hi)","color":"gray"}]`,
    `$data modify storage ${NS}:out failures append value {id:"$(id)",why:"expected $(lo)..$(hi) on $(who)"}`,
    `$execute store result storage ${NS}:out failures[-1].got int 1 run scoreboard players get $(who) ${NS}`,
    `scoreboard players add #fail ${NS} 1`,
]);

pack.fn('lib/check_same', [
    `execute if score #all ${NS} = #hits ${NS} run return run scoreboard players add #pass ${NS} 1`,
    `$tellraw @a [{"text":"[autotest] FAIL ","color":"red"},{"text":"$(id)","color":"white"},{"text":"  - rolls with any head: ","color":"gray"},{"score":{"name":"#all","objective":"${NS}"},"color":"yellow"},{"text":", with this head: ","color":"gray"},{"score":{"name":"#hits","objective":"${NS}"},"color":"yellow"}]`,
    `$data modify storage ${NS}:out failures append value {id:"$(id)",why:"another head dropped"}`,
    `scoreboard players add #fail ${NS} 1`,
]);

// One iteration of a sampling loop. Arguments come from storage autotest:q roll:
//   as    optional "execute as <runner> run " prefix, so the kill counts as a player kill
//   src   what to roll: `kill <victim>`, `mine <pos> <tool>` or `loot <table>`
//   pred  item predicate that counts as a hit; any  broader predicate; id  item id whose stack count is tracked
pack.fn('lib/roll', [
    `data modify block ${ROLL} Items set value []`,
    `$$(as)loot insert ${ROLL} $(src)`,
    `$execute if items block ${ROLL} container.* $(pred) run scoreboard players add #hits ${NS} 1`,
    `$execute if items block ${ROLL} container.* $(any) run scoreboard players add #all ${NS} 1`,
    `$execute store result score #c ${NS} run data get block ${ROLL} Items[{id:"$(id)"}].count`,
    `scoreboard players operation #max ${NS} > #c ${NS}`,
    `scoreboard players operation #min ${NS} < #c ${NS}`,
    `scoreboard players remove #n ${NS} 1`,
    `execute if score #n ${NS} matches 1.. run function ${NS}:lib/roll with storage ${NS}:q roll`,
]);

pack.fn('failures', [
    `execute if score #fail ${NS} matches 0 run return run tellraw @a {"text":"[autotest] no failures recorded","color":"green"}`,
    `tellraw @a [{"text":"[autotest] failures:\\n","color":"red"},{"nbt":"failures[].id","storage":"${NS}:out","separator":"\\n","color":"white"}]`,
]);

pack.fn('lab', [
    `execute in minecraft:overworld run forceload add ${FORCELOAD}`,
    `execute in minecraft:overworld run tp @s ${LAB.x} ${LAB.y + 3} ${LAB.z}`,
    `tellraw @s {"text":"[autotest] teleported to the lab. The area stays loaded until /function ${NS}:cleanup","color":"gray"}`,
]);

pack.fn('cleanup', [
    `execute in minecraft:overworld run forceload remove ${FORCELOAD}`,
    'tag @a remove autotest.runner',
    `scoreboard objectives remove ${NS}`,
    `data remove storage ${NS}:out failures`,
    `data remove storage ${NS}:out skipped`,
    `data remove storage ${NS}:q stages`,
    `tellraw @a {"text":"[autotest] cleaned up (the lab blocks stay in the world at ${LAB.x} ${LAB.y} ${LAB.z})","color":"gray"}`,
]);

// ---- entry points ----
const suiteOrder = ['load', 'recipes', 'heads', 'mobs', 'blocks', 'stacks'].filter((s) => pack.suites.has(s));
const queue = (suites) => `data modify storage ${NS}:q stages set value [${suites.flatMap((s) => pack.suites.get(s)).map((f) => `{f:"${f}"}`).join(',')}]`;

pack.fn('run', [`function ${NS}:lib/begin`, queue(suiteOrder)]);
for (const suite of suiteOrder) {
    pack.fn(`run/${suite}`, [`function ${NS}:lib/begin`, queue([suite])]);
}

await pack.write(OUT);

console.log(`Wrote ${pack.files.size} files to ${path.relative(PATHS.root, OUT)}`);
console.log(`  recipes: ${recipeStats.crafts} crafter cases, ${recipeStats.cooks} furnace cases, ${recipeStats.stonecutting} stonecutting`);
console.log(`  heads: ${headStats.variants} variants over ${headStats.mobs} mobs, ${headStats.negatives} no-player checks`);
console.log(`  block tags: ${tagCount}, stack sizes: ${stackCount}, load objectives: ${objectiveCount}`);
console.log(`  suites: ${suiteOrder.join(', ')}`);
